using System.Diagnostics;
using System.Runtime.InteropServices;

namespace MustBeCleaner.TestKit.Sandboxing;

/// <summary>Thrown when a path would resolve outside the sandbox root.</summary>
public sealed class SandboxEscapeException(string attempted, string root)
    : InvalidOperationException($"Path '{attempted}' escapes sandbox root '{root}'.")
{
    public string Attempted { get; } = attempted;
    public string Root { get; } = root;
}

/// <summary>
/// Isolated temp folder for building real on-disk fixtures. Every path goes through
/// <see cref="Resolve"/>, which throws <see cref="SandboxEscapeException"/> for anything outside
/// <see cref="Root"/>. Disposing removes the whole tree (junctions are unlinked, never followed).
/// </summary>
public sealed class Sandbox : IDisposable
{
    public string Root { get; }

    public Sandbox()
    {
        var temp = Path.TrimEndingDirectorySeparator(Path.GetFullPath(Path.GetTempPath()));
        Root = Path.Combine(temp, "MustBeCleaner-sandbox-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(Root);
    }

    /// <summary>Returns the absolute path for <paramref name="relative"/>, or throws if it leaves the root.</summary>
    public string Resolve(string relative)
    {
        if (string.IsNullOrWhiteSpace(relative))
            throw new SandboxEscapeException(relative ?? "<null>", Root);

        string full;
        try { full = Path.GetFullPath(Path.Combine(Root, relative)); }
        catch (Exception e) when (e is ArgumentException or NotSupportedException or PathTooLongException)
        {
            throw new SandboxEscapeException(relative, Root);
        }

        var inside = full.StartsWith(Root + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase);
        if (!inside) throw new SandboxEscapeException(relative, Root);
        return full;
    }

    public string CreateDirectory(string relative)
    {
        var path = Resolve(relative);
        Directory.CreateDirectory(path);
        return path;
    }

    public string WriteFile(string relative, string content) => WriteFile(relative, System.Text.Encoding.UTF8.GetBytes(content));

    public string WriteFile(string relative, byte[] content)
    {
        var path = Resolve(relative);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllBytes(path, content);
        return path;
    }

    /// <summary>Deletes a file, folder tree, or junction. Junctions are unlinked without touching their target.</summary>
    public void Delete(string relative) => DeleteEntry(Resolve(relative));

    /// <summary>Creates an NTFS hard link. Returns false when the filesystem does not support it.</summary>
    public bool TryCreateHardLink(string linkRelative, string existingRelative)
    {
        var link = Resolve(linkRelative);
        var existing = Resolve(existingRelative);
        Directory.CreateDirectory(Path.GetDirectoryName(link)!);
        return OperatingSystem.IsWindows() && CreateHardLinkW(link, existing, IntPtr.Zero);
    }

    /// <summary>Creates a directory junction (no admin needed). Returns false when not permitted. The target must be inside the sandbox.</summary>
    public bool TryCreateJunction(string linkRelative, string targetRelative)
    {
        var link = Resolve(linkRelative);
        var target = Resolve(targetRelative);
        if (!OperatingSystem.IsWindows()) return false;
        Directory.CreateDirectory(Path.GetDirectoryName(link)!);
        Directory.CreateDirectory(target);

        var psi = new ProcessStartInfo("cmd.exe")
        {
            Arguments = $"/d /s /c \"mklink /J \"{link}\" \"{target}\"\"",
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            UseShellExecute = false,
            CreateNoWindow = true,
        };
        using var process = Process.Start(psi);
        if (process is null) return false;
        process.StandardOutput.ReadToEnd();
        process.StandardError.ReadToEnd();
        process.WaitForExit();
        return process.ExitCode == 0 && Directory.Exists(link);
    }

    /// <summary>Adds the fixed mix of awkward shapes the safety suites share. Links are added only when permitted.</summary>
    public void AddStandardTree()
    {
        // Case variants live in separate folders: NTFS is case-insensitive by default.
        WriteFile(@"case\Readme.TXT", "upper");
        WriteFile(@"case-variant\readme.txt", "lower");
        // 8.3-like literal names (not generated by the filesystem).
        WriteFile(@"short\PROGRA~1\SETUP~1.EXE", "stub");
        WriteFile("unicode\\r\u00e9sum\u00e9-\u65e5\u672c\u8a9e.txt", "unicode");
        CreateDirectory("empty");
        CreateDirectory(@"nested\empty\deeper");
        WriteFile(@"links\orig.bin", "payload");
        TryCreateHardLink(@"links\hard.bin", @"links\orig.bin");
        WriteFile(@"junction-target\inner.txt", "inner");
        TryCreateJunction(@"links\junction", "junction-target");
    }

    public void Dispose()
    {
        if (Directory.Exists(Root)) DeleteEntry(Root);
    }

    private static void DeleteEntry(string path)
    {
        var attrs = File.GetAttributes(path);
        var isDirectory = (attrs & FileAttributes.Directory) != 0;
        var isReparse = (attrs & FileAttributes.ReparsePoint) != 0;

        if (!isDirectory) { File.SetAttributes(path, FileAttributes.Normal); File.Delete(path); return; }
        if (isReparse) { Directory.Delete(path, recursive: false); return; }

        foreach (var child in Directory.EnumerateFileSystemEntries(path)) DeleteEntry(child);
        Directory.Delete(path, recursive: false);
    }

    [DllImport("kernel32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
    private static extern bool CreateHardLinkW(string newFileName, string existingFileName, IntPtr securityAttributes);
}
